-- Secuencia y tabla para LugarProduccion y Predio (Oracle 10g compatible)

CREATE SEQUENCE SEQ_LUGAR_PRODUCCION
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TBL_LUGAR_PRODUCCION (
    ID                  NUMBER(19,0)    NOT NULL,
    NOMBRE              VARCHAR2(200)   NOT NULL,
    DESCRIPCION         VARCHAR2(500),
    AREA                NUMBER(10,4),
    VEREDA              VARCHAR2(150),
    LATITUD             NUMBER(10,6),
    LONGITUD            NUMBER(10,6),
    ALTITUD             NUMBER(8,2),
    ACTIVO              NUMBER(1,0)     DEFAULT 1 NOT NULL,
    FECHA_CREACION      DATE            DEFAULT SYSDATE NOT NULL,
    FECHA_ACTUALIZACION DATE,
    MUNICIPIO_ID        NUMBER(19,0)    NOT NULL,
    CONSTRAINT PK_LUGAR_PRODUCCION PRIMARY KEY (ID),
    CONSTRAINT CK_LUGAR_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT FK_LUGAR_MUNICIPIO FOREIGN KEY (MUNICIPIO_ID)
        REFERENCES TBL_MUNICIPIO (ID)
);

CREATE INDEX IDX_LUGAR_MUNICIPIO ON TBL_LUGAR_PRODUCCION (MUNICIPIO_ID);

COMMENT ON TABLE TBL_LUGAR_PRODUCCION IS 'Lugares de producción agrícola asociados a municipios';

-- ─────────────────────────────────────────────────────────────────────────────

CREATE SEQUENCE SEQ_PREDIO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TBL_PREDIO (
    ID                      NUMBER(19,0)    NOT NULL,
    NOMBRE                  VARCHAR2(200)   NOT NULL,
    NUMERO_PREDIAL          VARCHAR2(30),
    MATRICULA_INMOBILIARIA  VARCHAR2(50),
    AREA                    NUMBER(10,4),
    VEREDA                  VARCHAR2(150),
    DESCRIPCION             VARCHAR2(500),
    LATITUD                 NUMBER(10,6),
    LONGITUD                NUMBER(10,6),
    ALTITUD                 NUMBER(8,2),
    ACTIVO                  NUMBER(1,0)     DEFAULT 1 NOT NULL,
    FECHA_CREACION          DATE            DEFAULT SYSDATE NOT NULL,
    FECHA_ACTUALIZACION     DATE,
    LUGAR_PRODUCCION_ID     NUMBER(19,0)    NOT NULL,
    CONSTRAINT PK_PREDIO PRIMARY KEY (ID),
    CONSTRAINT CK_PREDIO_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT FK_PREDIO_LUGAR FOREIGN KEY (LUGAR_PRODUCCION_ID)
        REFERENCES TBL_LUGAR_PRODUCCION (ID)
);

CREATE INDEX IDX_PREDIO_LUGAR       ON TBL_PREDIO (LUGAR_PRODUCCION_ID);
CREATE INDEX IDX_PREDIO_NUM_PREDIAL ON TBL_PREDIO (NUMERO_PREDIAL);

COMMENT ON TABLE TBL_PREDIO IS 'Predios rurales pertenecientes a lugares de producción';
