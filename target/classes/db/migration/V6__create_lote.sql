-- Secuencia y tabla para Lote (Oracle 10g compatible)

CREATE SEQUENCE SEQ_LOTE
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TBL_LOTE (
    ID                      NUMBER(19,0)    NOT NULL,
    NUMERO                  VARCHAR2(50)    NOT NULL,
    NOMBRE                  VARCHAR2(200),
    AREA                    NUMBER(10,4),
    ESTADO                  VARCHAR2(30)    NOT NULL,
    FECHA_SIEMBRA           DATE,
    FECHA_COSECHA_ESTIMADA  DATE,
    FECHA_COSECHA_REAL      DATE,
    LATITUD                 NUMBER(10,6),
    LONGITUD                NUMBER(10,6),
    ALTITUD                 NUMBER(8,2),
    FECHA_CREACION          DATE            DEFAULT SYSDATE NOT NULL,
    FECHA_ACTUALIZACION     DATE,
    CULTIVO_ID              NUMBER(19,0)    NOT NULL,
    CONSTRAINT PK_LOTE        PRIMARY KEY (ID),
    CONSTRAINT CK_LOTE_ESTADO CHECK (
        ESTADO IN ('ACTIVO','INACTIVO','EN_PRODUCCION','COSECHADO','ABANDONADO')
    ),
    CONSTRAINT FK_LOTE_CULTIVO FOREIGN KEY (CULTIVO_ID) REFERENCES TBL_CULTIVO (ID)
);

CREATE INDEX IDX_LOTE_CULTIVO ON TBL_LOTE (CULTIVO_ID);
CREATE INDEX IDX_LOTE_ESTADO  ON TBL_LOTE (ESTADO);

COMMENT ON TABLE TBL_LOTE IS 'Lotes individuales de producción dentro de un cultivo';

-- Tabla de relación Lote-Plaga (many-to-many)
-- TBL_PLAGA ya existe (creada en V4)
CREATE TABLE TBL_LOTE_PLAGA (
    LOTE_ID   NUMBER(19,0) NOT NULL,
    PLAGA_ID  NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_LOTE_PLAGA PRIMARY KEY (LOTE_ID, PLAGA_ID),
    CONSTRAINT FK_LP_LOTE    FOREIGN KEY (LOTE_ID)  REFERENCES TBL_LOTE (ID),
    CONSTRAINT FK_LP_PLAGA   FOREIGN KEY (PLAGA_ID) REFERENCES TBL_PLAGA (ID)
);
